param(
    [int]$Port = 3307
)

$ErrorActionPreference = "Stop"

$ProjectRoot = Split-Path -Parent $PSScriptRoot
$RuntimeDir = Join-Path $env:ProgramData "CodexBlog"
$DataDir = Join-Path $RuntimeDir "data"
$LogDir = Join-Path $RuntimeDir "logs"
$ConfigFile = Join-Path $RuntimeDir "my.ini"
$EnvFile = Join-Path $ProjectRoot ".env.local"
$BaseDir = if ($env:MYSQL_BASE_DIR) { $env:MYSQL_BASE_DIR } else { "E:\MySQL\MySQL Server 8.0" }
$Mysqld = Join-Path $BaseDir "bin\mysqld.exe"
$Mysql = Join-Path $BaseDir "bin\mysql.exe"

if (-not (Test-Path $Mysqld)) {
    throw "mysqld.exe was not found. Set MYSQL_BASE_DIR to the MySQL installation directory."
}

New-Item -ItemType Directory -Force -Path $RuntimeDir, $LogDir | Out-Null

$configLines = @(
    "[mysqld]",
    "basedir=`"$($BaseDir.Replace('\', '/'))`"",
    "datadir=$($DataDir.Replace('\', '/'))",
    "port=$Port",
    "bind-address=127.0.0.1",
    "mysqlx=0",
    "character-set-server=utf8mb4",
    "collation-server=utf8mb4_unicode_ci",
    "log-error=$($LogDir.Replace('\', '/'))/mysql-$Port.error.log"
)
Set-Content -LiteralPath $ConfigFile -Value $configLines -Encoding ascii

function New-HexSecret([int]$ByteCount) {
    $bytes = New-Object byte[] $ByteCount
    $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    $rng.GetBytes($bytes)
    $rng.Dispose()
    return (($bytes | ForEach-Object { $_.ToString("x2") }) -join "")
}

if (-not (Test-Path (Join-Path $DataDir "mysql"))) {
    Write-Host "Initializing local MySQL data directory: $DataDir"
    & $Mysqld --defaults-file="$ConfigFile" --initialize-insecure --console
    if ($LASTEXITCODE -ne 0) {
        throw "MySQL initialization failed."
    }
}

$listening = Get-NetTCPConnection -LocalPort $Port -State Listen -ErrorAction SilentlyContinue
if (-not $listening) {
    Write-Host "Starting local MySQL on 127.0.0.1:$Port"
    $stdout = Join-Path $LogDir "mysql-$Port.out.log"
    $stderr = Join-Path $LogDir "mysql-$Port.err.log"
    $launcher = Join-Path $PSScriptRoot "run-local-mysql.ps1"
    Start-Process -FilePath "powershell.exe" `
        -ArgumentList "-NoProfile", "-ExecutionPolicy", "Bypass", "-File", "`"$launcher`"", "-Port", "$Port" `
        -RedirectStandardOutput $stdout -RedirectStandardError $stderr `
        -WindowStyle Hidden | Out-Null

    $deadline = (Get-Date).AddSeconds(45)
    while ((Get-Date) -lt $deadline) {
        Start-Sleep -Milliseconds 800
        if (Get-NetTCPConnection -LocalPort $Port -State Listen -ErrorAction SilentlyContinue) {
            break
        }
    }
    if (-not (Get-NetTCPConnection -LocalPort $Port -State Listen -ErrorAction SilentlyContinue)) {
        throw "MySQL did not listen on 127.0.0.1:$Port within 45 seconds. See $stderr"
    }
}

$envExisted = Test-Path $EnvFile
if (-not $envExisted) {
    $rootPassword = New-HexSecret 24
    $appPassword = New-HexSecret 24
    $secretKey = New-HexSecret 32
    $adminPassword = New-HexSecret 16
    $cors = "http://localhost:4173,http://127.0.0.1:4173"
    $lines = @(
        "# Generated by scripts/setup-local-mysql.ps1 for local deployment verification.",
        "# Ignored by Git. Do not commit this file.",
        "ENVIRONMENT=production",
        "MYSQL_ROOT_PASSWORD=$rootPassword",
        "MYSQL_DATABASE=blog_db",
        "MYSQL_USER=bloguser",
        "MYSQL_PASSWORD=$appPassword",
        "DATABASE_URL=mysql+pymysql://bloguser:$appPassword@127.0.0.1:$Port/blog_db?charset=utf8mb4",
        "SECRET_KEY=$secretKey",
        "ADMIN_USERNAME=admin",
        "ADMIN_PASSWORD=$adminPassword",
        "ACCESS_TOKEN_EXPIRE_MINUTES=1440",
        "CORS_ORIGINS=$cors"
    )
    Set-Content -LiteralPath $EnvFile -Value $lines -Encoding utf8
    Write-Host "Generated .env.local. Credentials are not printed or committed."
}

$settings = @{}
Get-Content -LiteralPath $EnvFile | ForEach-Object {
    if ($_ -match '^([A-Za-z_][A-Za-z0-9_]*)=(.*)$') {
        $settings[$Matches[1]] = $Matches[2]
    }
}

$rootPassword = $settings["MYSQL_ROOT_PASSWORD"]
$appPassword = $settings["MYSQL_PASSWORD"]
$appUser = $settings["MYSQL_USER"]
$database = $settings["MYSQL_DATABASE"]

function Invoke-Mysql([string]$password, [string]$sql) {
    $previous = $env:MYSQL_PWD
    try {
        if ($password) {
            $env:MYSQL_PWD = $password
        } else {
            Remove-Item Env:MYSQL_PWD -ErrorAction SilentlyContinue
        }
        $sql | & $Mysql -h 127.0.0.1 -P $Port -u root --protocol=TCP --default-character-set=utf8mb4
        if ($LASTEXITCODE -ne 0) {
            throw "MySQL admin command failed."
        }
    } finally {
        if ($null -eq $previous) {
            Remove-Item Env:MYSQL_PWD -ErrorAction SilentlyContinue
        } else {
            $env:MYSQL_PWD = $previous
        }
    }
}

$setupSql = @"
ALTER USER 'root'@'localhost' IDENTIFIED BY '$rootPassword';
CREATE DATABASE IF NOT EXISTS ``$database`` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE USER IF NOT EXISTS '$appUser'@'127.0.0.1' IDENTIFIED BY '$appPassword';
CREATE USER IF NOT EXISTS '$appUser'@'localhost' IDENTIFIED BY '$appPassword';
ALTER USER '$appUser'@'127.0.0.1' IDENTIFIED BY '$appPassword';
ALTER USER '$appUser'@'localhost' IDENTIFIED BY '$appPassword';
GRANT ALL PRIVILEGES ON ``$database``.* TO '$appUser'@'127.0.0.1';
GRANT ALL PRIVILEGES ON ``$database``.* TO '$appUser'@'localhost';
FLUSH PRIVILEGES;
"@

if ($envExisted) {
    try {
        Invoke-Mysql $rootPassword $setupSql
    } catch {
        Invoke-Mysql "" $setupSql
    }
} else {
    try {
        Invoke-Mysql "" $setupSql
    } catch {
        Invoke-Mysql $rootPassword $setupSql
    }
}

$previous = $env:MYSQL_PWD
try {
    $env:MYSQL_PWD = $appPassword
    $result = & $Mysql -h 127.0.0.1 -P $Port -u $appUser --protocol=TCP -N -e "SELECT 1" $database
    if ($LASTEXITCODE -ne 0 -or $result.Trim() -ne "1") {
        throw "Application database connection check failed."
    }
} finally {
    if ($null -eq $previous) {
        Remove-Item Env:MYSQL_PWD -ErrorAction SilentlyContinue
    } else {
        $env:MYSQL_PWD = $previous
    }
}

Write-Host "MySQL is ready: 127.0.0.1:$Port/$database (loopback only)"

